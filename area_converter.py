# โปรแกรมแปลงหน่วยพื้นที่อัจฉริยะ
print("===== โปรแกรมแปลงหน่วยพื้นที่อัจฉริยะ =====")

# รับค่าพื้นที่
area = float(input("ป้อนพื้นที่ (ตารางเมตร): "))

# แปลงหน่วย
square_wa = area / 4
ngan = area / 400
rai = area / 1600
square_km = area / 1_000_000

# แสดงผลลัพธ์
print("\n===== ผลลัพธ์ =====")
print(f"ตารางเมตร     : {area:,.2f} ตร.ม.")
print(f"ตารางวา       : {square_wa:,.2f} ตร.ว.")
print(f"งาน            : {ngan:,.2f} งาน")
print(f"ไร่            : {rai:,.2f} ไร่")
print(f"ตารางกิโลเมตร : {square_km:,.6f} ตร.กม.")
