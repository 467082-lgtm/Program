# โค้ดเวอร์ชันใหม่: โปรแกรมคำนวณและแปลงหน่วยพื้นที่อัจฉริยะ
print("--- โปรแกรมคำนวณพื้นที่และแปลงหน่วยที่ดินอัจฉริยะ ---")

# 1. รับค่ากว้างและยาวจากผู้ใช้ (รองรับทศนิยม)
w = float(input("ป้อนความกว้าง (เมตร): "))
l = float(input("ป้อนความยาว (เมตร): "))

# 2. คำนวณพื้นที่เป็นตารางเมตร
sq_meters = w * l
print(f"\nพื้นที่ที่คำนวณได้ = {sq_meters:,.2f} ตารางเมตร")

# 3. แปลงหน่วยอัจฉริยะ (1 ตารางวา = 4 ตารางเมตร, 1 งาน = 100 ตารางวา, 1 ไร่ = 400 ตารางวา)
sq_wa = sq_meters / 4

rai = int(sq_wa // 400)          # หาจำนวนไร่
remaining_wa = sq_wa % 400       # ตารางวาที่เหลือจากไร่

ngan = int(remaining_wa // 100)  # หาจำนวนงาน
wa = remaining_wa % 100          # ตารางวาที่เหลือจากงาน

# 4. แสดงผลลัพธ์การแปลงหน่วยแบบไทย
print("------------------------------------------")
print(f"คิดเป็นหน่วยไทย: {rai} ไร่  {ngan} งาน  {wa:.2f} ตารางวา")
print("------------------------------------------")
